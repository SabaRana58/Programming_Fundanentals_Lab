#include <iostream>
using namespace std;
int main() {
    cout << "28 / 4 - 2 = " << 28 / 4 - 2 << endl; // 5
    cout << "6 + 12 * 2 - 8 = " << 6 + 12 * 2 - 8 << endl; // 22
    cout << "4 + 8 * 2 = " << 4 + 8 * 2 << endl; // 20
    cout << "6 + 17 % 3 - 2 = " << 6 + 17 % 3 - 2 << endl; // 6
    cout << "2 + 22 * (9 - 7) = " << 2 + 22 * (9 - 7) << endl; // 46
    cout << "(8 + 7) * 2 = " << (8 + 7) * 2 << endl; // 30
    cout << "(16 + 7) % 2 - 1 = " << (16 + 7) % 2 - 1 << endl; // 0
    cout << "12 / (10 - 6) = " << 12 / (10 - 6) << endl; // 3
    cout << "(19 - 3) * (2 + 2) / 4 = " << (19 - 3) * (2 + 2) / 4 << endl; // 16
    return 0;
}
